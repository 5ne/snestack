import * as os from "os";
import * as path from "path";
import { Db } from "../../../../src/core/db";
import { TraderAgent } from "../../../../src/domains/financial/agents/traderAgent";
import type { Signal, EquityData } from "../../../../src/core/models";

function tmpDb(): Db {
  return new Db(
    path.join(os.tmpdir(), `fstack-trader-${Date.now()}-${Math.random()}.db`)
  );
}

function makeSignal(
  ticker: string,
  rec: Signal["recommendation"] = "BUY",
  confidence = 0.8
): Signal {
  return {
    ticker,
    recommendation: rec,
    confidence,
    reasoning: `Test signal for ${ticker}`,
    date: new Date(),
    fromWatchlist: false,
    createdAt: new Date(),
  };
}

function makeEquity(overrides: Partial<EquityData> = {}): EquityData {
  return {
    ticker: "TEST",
    redFlags: [],
    timestamp: new Date(),
    ...overrides,
  };
}

// isActionable/byConfidenceDesc aren't exported — mirror the same filter/sort
// TraderAgent.sendBatchEmail applies internally, so tests can build the actionNow
// array the same way the class does.
const ACTION_THRESHOLD = 0.75;
function actionNowOf(signals: Signal[]): Signal[] {
  return signals
    .filter((s) => (s.recommendation === "BUY" || s.recommendation === "SELL") && s.confidence > ACTION_THRESHOLD)
    .sort((a, b) => b.confidence - a.confidence);
}

describe("TraderAgent.buildSubject", () => {
  it("builds correct subject line", () => {
    const buys = [makeSignal("NVDA"), makeSignal("AAPL")];
    const sells = [makeSignal("TSLA", "SELL")];
    const holds = [makeSignal("META", "HOLD")];
    const subject = TraderAgent.buildSubject(buys, sells, holds, [], {}, "2024-01-15");
    expect(subject).toContain("2024-01-15");
    expect(subject).toContain("2 BUY");
    expect(subject).toContain("1 SELL");
    expect(subject).toContain("1 HOLD");
  });

  it("handles empty arrays", () => {
    const subject = TraderAgent.buildSubject([], [], [], [], {}, "2024-01-15");
    expect(subject).toContain("0 BUY");
    expect(subject).toContain("0 SELL");
  });

  it("appends an ACT NOW count when signals exceed the confidence threshold", () => {
    const buys = [makeSignal("NVDA", "BUY", 0.9)];
    const subject = TraderAgent.buildSubject(buys, [], [], actionNowOf(buys), {}, "2024-01-15");
    expect(subject).toContain("ACT NOW");
    expect(subject).toContain("1 ACT NOW");
  });

  it("omits ACT NOW when nothing exceeds the threshold", () => {
    const buys = [makeSignal("NVDA", "BUY", 0.6)];
    const subject = TraderAgent.buildSubject(buys, [], [], actionNowOf(buys), {}, "2024-01-15");
    expect(subject).not.toContain("ACT NOW");
  });

  it("notes a data/analysis issue count in the subject when issues are present", () => {
    const buys = [makeSignal("NVDA", "BUY", 0.6)];
    const subject = TraderAgent.buildSubject(
      buys,
      [],
      [],
      [],
      { NVDA: ["No live quote data — Finnhub fetch failed"] },
      "2024-01-15"
    );
    expect(subject).toContain("1 data issue");
  });

  it("pluralizes the issue count when more than one ticker has an issue", () => {
    const buys = [makeSignal("NVDA", "BUY", 0.6), makeSignal("AAPL", "BUY", 0.6)];
    const subject = TraderAgent.buildSubject(
      buys,
      [],
      [],
      [],
      { NVDA: ["issue a"], AAPL: ["issue b"] },
      "2024-01-15"
    );
    expect(subject).toContain("2 data issues");
  });

  it("omits the issue count when there are no issues", () => {
    const buys = [makeSignal("NVDA", "BUY", 0.6)];
    const subject = TraderAgent.buildSubject(buys, [], [], [], {}, "2024-01-15");
    expect(subject).not.toContain("data issue");
  });
});

describe("TraderAgent.buildEmailBody", () => {
  it("includes BUY section when buys present", () => {
    const buys = [makeSignal("NVDA")];
    const body = TraderAgent.buildEmailBody(buys, [], [], [], {}, {}, "2024-01-15");
    expect(body).toContain("BUY SIGNALS");
    expect(body).toContain("NVDA");
    expect(body).toContain("80%");
  });

  it("includes SELL section when sells present", () => {
    const sells = [makeSignal("TSLA", "SELL")];
    const body = TraderAgent.buildEmailBody([], sells, [], [], {}, {}, "2024-01-15");
    expect(body).toContain("SELL SIGNALS");
    expect(body).toContain("TSLA");
  });

  it("includes HOLD section when holds present", () => {
    const holds = [makeSignal("META", "HOLD")];
    const body = TraderAgent.buildEmailBody([], [], holds, [], {}, {}, "2024-01-15");
    expect(body).toContain("HOLD SIGNALS");
    expect(body).toContain("META");
  });

  it("includes date and footer", () => {
    const body = TraderAgent.buildEmailBody([], [], [], [], {}, {}, "2024-01-15");
    expect(body).toContain("2024-01-15");
    expect(body).toContain("Generated by fstack");
  });

  it("includes reasoning for buys", () => {
    const buy = makeSignal("NVDA");
    buy.reasoning = "AI chip leader with strong moat";
    const body = TraderAgent.buildEmailBody([buy], [], [], [], {}, {}, "2024-01-15");
    expect(body).toContain("AI chip leader with strong moat");
  });

  it("includes an ACT NOW block for high-confidence signals", () => {
    const buys = [makeSignal("NVDA", "BUY", 0.9)];
    const body = TraderAgent.buildEmailBody(buys, [], [], actionNowOf(buys), {}, {}, "2024-01-15");
    expect(body).toContain("ACT NOW");
    expect(body).toContain("NVDA");
  });

  it("includes financials for a ticker when equity data is present", () => {
    const buys = [makeSignal("NVDA")];
    const equities = { NVDA: makeEquity({ peRatio: 32.3, pbRatio: 26.2, dividendYield: 0.001 }) };
    const body = TraderAgent.buildEmailBody(buys, [], [], [], equities, {}, "2024-01-15");
    expect(body).toContain("Financials:");
    expect(body).toContain("P/E 32.3");
    expect(body).toContain("P/B 26.2");
  });

  it("omits the financials line when no equity data is present for a ticker", () => {
    const buys = [makeSignal("NVDA")];
    const body = TraderAgent.buildEmailBody(buys, [], [], [], {}, {}, "2024-01-15");
    expect(body).not.toContain("Financials:");
  });

  it("includes a top-of-email issues block and per-ticker issue notes when issues are present", () => {
    const buys = [makeSignal("NVDA")];
    const issues = { NVDA: ["No live quote data — Finnhub fetch failed"] };
    const body = TraderAgent.buildEmailBody(buys, [], [], [], {}, issues, "2024-01-15");
    expect(body).toContain("DATA & ANALYSIS ISSUES");
    expect(body).toContain("No live quote data — Finnhub fetch failed");
    expect(body).toContain("Issues:");
  });

  it("flags an affected HOLD ticker inline without a separate issues block entry duplicated per line", () => {
    const holds = [makeSignal("META", "HOLD")];
    const issues = { META: ["CFO synthesis call failed: timeout"] };
    const body = TraderAgent.buildEmailBody([], [], holds, [], {}, issues, "2024-01-15");
    expect(body).toContain("META");
    expect(body).toMatch(/META.*⚠/);
  });

  it("omits the issues block entirely when there are no issues", () => {
    const buys = [makeSignal("NVDA")];
    const body = TraderAgent.buildEmailBody(buys, [], [], [], {}, {}, "2024-01-15");
    expect(body).not.toContain("DATA & ANALYSIS ISSUES");
  });
});

describe("TraderAgent confidence sorting", () => {
  it("sendBatchEmail's actionable filter selects only BUY/SELL over the threshold", () => {
    const signals = [
      makeSignal("LOW_BUY", "BUY", 0.5),
      makeSignal("HIGH_BUY", "BUY", 0.9),
      makeSignal("HIGH_HOLD", "HOLD", 0.95),
      makeSignal("HIGH_SELL", "SELL", 0.8),
    ];
    const action = actionNowOf(signals);
    expect(action.map((s) => s.ticker)).toEqual(["HIGH_BUY", "HIGH_SELL"]);
  });

  it("buildEmailBody's BUY section lists highest confidence first when pre-sorted", () => {
    const buys = [makeSignal("LOW", "BUY", 0.6), makeSignal("HIGH", "BUY", 0.9)].sort(
      (a, b) => b.confidence - a.confidence
    );
    const body = TraderAgent.buildEmailBody(buys, [], [], [], {}, {}, "2024-01-15");
    expect(body.indexOf("HIGH")).toBeLessThan(body.indexOf("LOW"));
  });
});

describe("TraderAgent database interaction", () => {
  let db: Db;
  let agent: TraderAgent;

  beforeEach(() => {
    db = tmpDb();
    agent = new TraderAgent(db, "from@test.com", "password", "to@test.com");
  });

  afterEach(() => {
    db.close();
  });

  it("stores signals in DB after send failure", async () => {
    db.addTicker("NVDA", "NVIDIA", "PUBLIC");
    const signals = [makeSignal("NVDA")];

    // Mock sendEmail to return false (failure)
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    jest.spyOn(agent as any, "sendEmail").mockResolvedValueOnce(false);

    await agent.sendBatchEmail(signals, {}, {}, "2024-01-15");

    // Signals should be stored and queued for retry
    const pending = db.getPendingNotifications();
    expect(pending.length).toBeGreaterThan(0);
  });

  it("retryPendingNotifications returns 0 when nothing pending", async () => {
    const count = await agent.retryPendingNotifications();
    expect(count).toBe(0);
  });

  it("sendBatchEmail returns true for empty signals", async () => {
    const result = await agent.sendBatchEmail([]);
    expect(result).toBe(true);
  });

  it("threads the issues map through to the sent subject and body", async () => {
    db.addTicker("NVDA", "NVIDIA", "PUBLIC");
    const signals = [makeSignal("NVDA")];
    const issues = { NVDA: ["No live quote data — Finnhub fetch failed"] };

    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const sendEmailSpy = jest
      .spyOn(agent as any, "sendEmail")
      .mockResolvedValueOnce(true);

    await agent.sendBatchEmail(signals, {}, issues, "2024-01-15");

    expect(sendEmailSpy).toHaveBeenCalledTimes(1);
    const [subject, text, html] = sendEmailSpy.mock.calls[0];
    expect(subject).toContain("1 data issue");
    expect(text).toContain("No live quote data — Finnhub fetch failed");
    expect(html).toContain("No live quote data");
  });
});
