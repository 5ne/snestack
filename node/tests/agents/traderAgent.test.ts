import * as os from "os";
import * as path from "path";
import { Db } from "../../src/core/db";
import { TraderAgent } from "../../src/agents/traderAgent";
import type { Signal } from "../../src/core/models";

function tmpDb(): Db {
  return new Db(
    path.join(os.tmpdir(), `fstack-trader-${Date.now()}-${Math.random()}.db`)
  );
}

function makeSignal(ticker: string, rec: Signal["recommendation"] = "BUY"): Signal {
  return {
    ticker,
    recommendation: rec,
    confidence: 0.8,
    reasoning: `Test signal for ${ticker}`,
    date: new Date(),
    fromWatchlist: false,
    createdAt: new Date(),
  };
}

describe("TraderAgent.buildSubject", () => {
  it("builds correct subject line", () => {
    const buys = [makeSignal("NVDA"), makeSignal("AAPL")];
    const sells = [makeSignal("TSLA", "SELL")];
    const holds = [makeSignal("META", "HOLD")];
    const subject = TraderAgent.buildSubject(buys, sells, holds, "2024-01-15");
    expect(subject).toContain("2024-01-15");
    expect(subject).toContain("2 BUY");
    expect(subject).toContain("1 SELL");
    expect(subject).toContain("1 HOLD");
  });

  it("handles empty arrays", () => {
    const subject = TraderAgent.buildSubject([], [], [], "2024-01-15");
    expect(subject).toContain("0 BUY");
    expect(subject).toContain("0 SELL");
  });
});

describe("TraderAgent.buildEmailBody", () => {
  it("includes BUY section when buys present", () => {
    const buys = [makeSignal("NVDA")];
    const body = TraderAgent.buildEmailBody(buys, [], [], "2024-01-15");
    expect(body).toContain("BUY SIGNALS");
    expect(body).toContain("NVDA");
    expect(body).toContain("80%");
  });

  it("includes SELL section when sells present", () => {
    const sells = [makeSignal("TSLA", "SELL")];
    const body = TraderAgent.buildEmailBody([], sells, [], "2024-01-15");
    expect(body).toContain("SELL SIGNALS");
    expect(body).toContain("TSLA");
  });

  it("includes HOLD section when holds present", () => {
    const holds = [makeSignal("META", "HOLD")];
    const body = TraderAgent.buildEmailBody([], [], holds, "2024-01-15");
    expect(body).toContain("HOLD SIGNALS");
    expect(body).toContain("META");
  });

  it("includes date and footer", () => {
    const body = TraderAgent.buildEmailBody([], [], [], "2024-01-15");
    expect(body).toContain("2024-01-15");
    expect(body).toContain("Generated by fstack");
  });

  it("includes reasoning for buys", () => {
    const buy = makeSignal("NVDA");
    buy.reasoning = "AI chip leader with strong moat";
    const body = TraderAgent.buildEmailBody([buy], [], [], "2024-01-15");
    expect(body).toContain("AI chip leader with strong moat");
  });
});

describe("TraderAgent database interaction", () => {
  let db: Db;
  let agent: TraderAgent;

  beforeEach(() => {
    db = tmpDb();
    agent = new TraderAgent(db, "from@test.com", "password", "to@test.com");
  });

  afterEach(() => {
    db.close();
  });

  it("stores signals in DB after send failure", async () => {
    db.addTicker("NVDA", "NVIDIA", "PUBLIC");
    const signals = [makeSignal("NVDA")];

    // Mock sendEmail to return false (failure)
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    jest.spyOn(agent as any, "sendEmail").mockResolvedValueOnce(false);

    await agent.sendBatchEmail(signals, "2024-01-15");

    // Signals should be stored and queued for retry
    const pending = db.getPendingNotifications();
    expect(pending.length).toBeGreaterThan(0);
  });

  it("retryPendingNotifications returns 0 when nothing pending", async () => {
    const count = await agent.retryPendingNotifications();
    expect(count).toBe(0);
  });

  it("sendBatchEmail returns true for empty signals", async () => {
    const result = await agent.sendBatchEmail([]);
    expect(result).toBe(true);
  });
});
